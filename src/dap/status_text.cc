std::string Status::str () const
{
    const char *mac = lookup (maccodes, maccode);
    std::string macstr = mac ? mac : "Unexpected MACCODE " + octal (maccode, 4);
    const char *mic = nullptr;
    switch (maccode) {
    case 2: case 8: case 9:
        mic = lookup (miccodes_289, miccode); break;
    case 0: case 1: case 4: case 5: case 6: case 7:
        mic = lookup (miccodes_rms, miccode); break;
    case 10:
        mic = lookup (miccodes_10, miccode); break;
    default:
        return macstr + ": ";
    }
    return macstr + ": "
        + (mic ? mic : "Unexpected MICCODE " + octal (miccode, 4));
}

