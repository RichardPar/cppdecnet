template <std::size_t N>
const char *lookup (const Text (&t)[N], unsigned code)
{
    auto it = std::lower_bound (std::begin (t), std::end (t), code,
        [] (const Text &e, unsigned c) { return e.code < c; });
    return it != std::end (t) && it->code == code ? it->text : nullptr;
}

std::string octal (unsigned v, int width)
{
    char buf[16];
    std::snprintf (buf, sizeof buf, "%0*o", width, v);
    return buf;
}

